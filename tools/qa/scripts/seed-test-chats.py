#!/usr/bin/env python3
"""Seed only the isolated Tatrak QA server; execute inside its Prosody container."""

import asyncio
import inspect
import json
import ssl
import uuid

import slixmpp


DOMAIN = "10.0.2.2"
PASSWORD = "secret123"  # Disposable local QA accounts created by the test-server image.
CERTIFICATE = f"/var/lib/prosody/certs/{DOMAIN}.crt"


class SeedClient(slixmpp.ClientXMPP):
    def __init__(self, username, peer, token):
        super().__init__(f"{username}@{DOMAIN}/qa-seed", PASSWORD)
        self.seed_username = username
        self.peer = f"{peer}@{DOMAIN}"
        self.peer_name = peer
        self.token = token
        self.ready = asyncio.Event()
        self.received = asyncio.Event()
        self.error = None
        # Trust only the certificate generated by this isolated container. Hostname
        # checking remains enabled for the XMPP domain, even though TCP uses localhost.
        self.ssl_context = ssl.create_default_context(cafile=CERTIFICATE)
        self.add_event_handler("session_start", self.start)
        self.add_event_handler("failed_auth", self.failed_auth)
        self.add_event_handler("presence_subscribe", self.subscribe)
        self.add_event_handler("message", self.message)

    async def start(self, _):
        try:
            await self.get_roster(timeout=10)
            update = self.update_roster(self.peer, name=self.peer_name, timeout=10)
            if inspect.isawaitable(update):
                await update
            self.send_presence()
        except Exception as exc:
            self.error = f"{type(exc).__name__}: {exc}"
        finally:
            self.ready.set()

    def failed_auth(self, _):
        self.error = "Authentication failed for disposable QA account"
        self.ready.set()

    def subscribe(self, presence):
        if str(presence["from"].bare) == self.peer:
            self.send_presence(pto=self.peer, ptype="subscribed")

    def message(self, stanza):
        if str(stanza["from"].bare) == self.peer and str(stanza["body"]).startswith(self.token):
            self.received.set()


async def seed():
    token = f"tatrak-qa-bootstrap-{uuid.uuid4().hex}"
    clients = [SeedClient("tester", "friend", token), SeedClient("friend", "tester", token)]
    try:
        await asyncio.gather(*(client.connect(host="127.0.0.1", port=5222) for client in clients))
        await asyncio.wait_for(asyncio.gather(*(client.ready.wait() for client in clients)), 35)
        for client in clients:
            if client.error:
                raise RuntimeError(f"{client.seed_username}: {client.error}")
            client.send_presence(pto=client.peer, ptype="subscribe")
            # Both fixed QA accounts explicitly authorize each other's subscription.
            client.send_presence(pto=client.peer, ptype="subscribed")

        # Poll the authoritative server roster, rather than assuming stanza submission
        # means a mutual subscription has been established.
        for _ in range(20):
            await asyncio.gather(*(client.get_roster(timeout=5) for client in clients))
            if all(client.client_roster[client.peer]["subscription"] == "both" for client in clients):
                break
            await asyncio.sleep(0.25)
        else:
            raise RuntimeError("Mutual roster subscriptions did not reach 'both'")

        for client in clients:
            client.send_message(mto=client.peer, mbody=f"{token} from {client.seed_username}", mtype="chat")
        await asyncio.wait_for(asyncio.gather(*(client.received.wait() for client in clients)), 15)
        print(json.dumps({
            "status": "seeded",
            "token": token,
            "accounts": [
                {"jid": str(client.boundjid.bare), "contact": client.peer,
                 "contact_name": client.client_roster[client.peer]["name"],
                 "subscription": client.client_roster[client.peer]["subscription"],
                 "bootstrap_received": client.received.is_set()}
                for client in clients
            ],
        }, indent=2))
    finally:
        await asyncio.gather(*(client.disconnect(wait=1) for client in clients), return_exceptions=True)


if __name__ == "__main__":
    asyncio.run(asyncio.wait_for(seed(), 70))
