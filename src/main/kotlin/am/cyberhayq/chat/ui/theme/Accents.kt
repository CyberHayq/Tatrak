/**
 * Accent presets. Colours live in `tatrak_accent_colors.xml` (light and night, generated by
 * `art/tatrak/gen_accents.py`) behind one overlay per accent, which the XML screens apply in
 * `BaseActivity` and Compose reads back in [resolveAccent], so both always agree.
 */
enum class Accent(
    val key: String,
    @param:StyleRes val overlay: Int,
    @param:StringRes val label: Int,
    val swatch: Color,
    /** A signature theme with its own surfaces; picked in its own group. */
    val signature: Boolean = false,
    /** An editor palette (One Dark, Dracula: own night and day surfaces); picked in its own group. */
    val palette: Boolean = false,
) {
    BLUE("blue", R.style.ThemeOverlay_Tatrak_Accent_Blue, R.string.tatrak_accent_blue, Color(0xFF298ACF)),
    CYAN("cyan", R.style.ThemeOverlay_Tatrak_Accent_Cyan, R.string.tatrak_accent_cyan, Color(0xFF1EA6B6)),
    SEA("sea", R.style.ThemeOverlay_Tatrak_Accent_Sea, R.string.tatrak_accent_sea, Color(0xFF0B6F7A)),
    GREEN("green", R.style.ThemeOverlay_Tatrak_Accent_Green, R.string.tatrak_accent_green, Color(0xFF3FA34D)),
    VIOLET("violet", R.style.ThemeOverlay_Tatrak_Accent_Violet, R.string.tatrak_accent_violet, Color(0xFF8E63CE)),
    PINK("pink", R.style.ThemeOverlay_Tatrak_Accent_Pink, R.string.tatrak_accent_pink, Color(0xFFE05A8D)),
    ORANGE("orange", R.style.ThemeOverlay_Tatrak_Accent_Orange, R.string.tatrak_accent_orange, Color(0xFFEB8A2F)),
    RED("red", R.style.ThemeOverlay_Tatrak_Accent_Red, R.string.tatrak_accent_red, Color(0xFFD9534F)),
    ONEDARK("onedark", R.style.ThemeOverlay_Tatrak_Accent_Onedark, R.string.tatrak_accent_onedark, Color(0xFF61AFEF), palette = true),
    DRACULA("dracula", R.style.ThemeOverlay_Tatrak_Accent_Dracula, R.string.tatrak_accent_dracula, Color(0xFFBD93F9), palette = true),
    EMBER("ember", R.style.ThemeOverlay_Tatrak_Accent_Ember, R.string.tatrak_accent_ember, Color(0xFFB3121B), signature = true),
    STEEL("steel", R.style.ThemeOverlay_Tatrak_Accent_Steel, R.string.tatrak_accent_steel, Color(0xFF3877A4), signature = true),
    CRIMSON("crimson", R.style.ThemeOverlay_Tatrak_Accent_Crimson, R.string.tatrak_accent_crimson, Color(0xFFB01E2F), signature = true),
