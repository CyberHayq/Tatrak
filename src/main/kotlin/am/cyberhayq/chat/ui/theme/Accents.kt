    companion object {
        @JvmStatic fun of(key: String?): Accent = entries.firstOrNull { it.key == key } ?: BLUE
    }
}

@Immutable
data class AccentColors(
    val primary: Color,
    val onPrimary: Color,
    val primaryContainer: Color,
    val onPrimaryContainer: Color,
    val secondary: Color,
    val link: Color,
    val bubbleOutgoing: Color,
    val timeOutgoing: Color,
    val checkRead: Color,
    val unreadBadge: Color,
    val accentIn: Color,
    val accentOut: Color,
)

/** The overlay's colours for light or night, independent of the context's own mode. */
fun resolveAccent(context: Context, accent: Accent, dark: Boolean): AccentColors {
    val configuration =
        Configuration(context.resources.configuration).apply {
            uiMode =
                (uiMode and Configuration.UI_MODE_NIGHT_MASK.inv()) or
                    if (dark) Configuration.UI_MODE_NIGHT_YES else Configuration.UI_MODE_NIGHT_NO
        }
    val themed = ContextThemeWrapper(context.createConfigurationContext(configuration), accent.overlay)
    val value = TypedValue()
    fun color(attr: Int): Color {
        check(themed.theme.resolveAttribute(attr, value, true)) { "accent overlay misses an attribute" }
        return Color(value.data)
    }
    return AccentColors(
        primary = color(androidx.appcompat.R.attr.colorPrimary),
        onPrimary = color(com.google.android.material.R.attr.colorOnPrimary),
        primaryContainer = color(com.google.android.material.R.attr.colorPrimaryContainer),
        onPrimaryContainer = color(com.google.android.material.R.attr.colorOnPrimaryContainer),
        secondary = color(com.google.android.material.R.attr.colorSecondary),
        link = color(R.attr.tatrakLink),
        bubbleOutgoing = color(R.attr.tatrakBubbleOutgoing),
        timeOutgoing = color(R.attr.tatrakTimeOutgoing),
        checkRead = color(R.attr.tatrakCheckRead),
        unreadBadge = color(R.attr.tatrakUnreadBadge),
        accentIn = color(R.attr.tatrakAccentIn),
        accentOut = color(R.attr.tatrakAccentOut),
    )
}

/** The accent in effect (Sea while none was chosen under Slate and Sea), updated live when the setting changes. */
@Composable
fun rememberAccent(style: TatrakStyle = TatrakStyle.remember()): Accent =
    TatrakStyle.effectiveAccent(style, rememberStringPreference(AppSettings.ACCENT))

/**
 * Whether the system's wallpaper colours (Material You) replace the accent: the same
 * setting `BaseActivity` applies to the XML screens; only on Android 12+.
 */
@Composable
fun rememberDynamicColors(): Boolean {
    // the same availability check as AppSettings.isDynamicColorsDesired (Android 12+, and 12/12L only on listed makers)
    if (!DynamicColors.isDynamicColorAvailable()) return false
    val default = LocalContext.current.resources.getBoolean(R.bool.dynamic_colors)
    return rememberPreference(AppSettings.DYNAMIC_COLORS) { it.getBoolean(AppSettings.DYNAMIC_COLORS, default) }
}

/** The accent's colour slots filled from the system's dynamic scheme (Android 12+). */
fun dynamicAccent(context: Context, dark: Boolean): AccentColors {
    val scheme = if (dark) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
    return AccentColors(
        primary = scheme.primary,
        onPrimary = scheme.onPrimary,
        primaryContainer = if (dark) scheme.surfaceContainerHigh else scheme.primary,
        onPrimaryContainer = if (dark) scheme.onSurface else scheme.onPrimary,
        secondary = scheme.secondary,
        link = scheme.primary,
        bubbleOutgoing = if (dark) scheme.primaryContainer.copy(alpha = 1f) else scheme.primaryContainer,
        timeOutgoing = scheme.onPrimaryContainer.copy(alpha = 0.6f),
        checkRead = scheme.primary,
        unreadBadge = scheme.primary,
        accentIn = scheme.primary,
        accentOut = scheme.onPrimaryContainer,
    )
}

/** A string setting as Compose state, updated live when it changes. */
@Composable
fun rememberStringPreference(key: String): String? = rememberPreference(key) { it.getString(key, null) }

/** A setting as Compose state, updated live when it changes. */
@Composable
fun <T> rememberPreference(key: String, read: (SharedPreferences) -> T): T {
    val context = LocalContext.current
    val preferences = remember(context) { PreferenceManager.getDefaultSharedPreferences(context) }
    var value by remember(preferences, key) { mutableStateOf(read(preferences)) }
    DisposableEffect(preferences, key) {
        // SharedPreferences keeps listeners weakly; this lambda holds it for the composition
        val listener =
            SharedPreferences.OnSharedPreferenceChangeListener { prefs, changed ->
                if (changed == key) value = read(prefs)
            }
        preferences.registerOnSharedPreferenceChangeListener(listener)
        onDispose { preferences.unregisterOnSharedPreferenceChangeListener(listener) }
    }
    return value
}
